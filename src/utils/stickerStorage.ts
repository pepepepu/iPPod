import { homeContent, type PlacedSticker } from '../content/homeContent';

const STICKER_STORAGE_KEY = '@ippod:placed-stickers-v4';

function randomBetween(min: number, max: number): number {
  return min + Math.random() * (max - min);
}

function isInsideForbiddenZone(x: number, y: number): boolean {
  const insideLcd = Math.abs(x) < 1.03 && y > 0.32 && y < 1.92;
  const distToWheel = Math.hypot(x, y + 0.98);
  const insideWheel = distToWheel < 0.96;
  return insideLcd || insideWheel;
}

function sampleScreenBorderPoint(): [number, number] {
  const borderSide = Math.floor(Math.random() * 4);

  if (borderSide === 0) {
    return [randomBetween(-1.16, 1.16), randomBetween(1.95, 2.14)];
  }
  if (borderSide === 1) {
    const side = Math.random() > 0.5 ? 1 : -1;
    return [side * randomBetween(0.45, 1.15), randomBetween(0.18, 0.3)];
  }
  if (borderSide === 2) {
    return [randomBetween(-1.24, -1.05), randomBetween(0.3, 2.02)];
  }
  return [randomBetween(1.05, 1.24), randomBetween(0.3, 2.02)];
}

function sampleAroundWheelPoint(): [number, number] {
  for (let i = 0; i < 50; i += 1) {
    const x = randomBetween(-1.22, 1.22);
    const y = randomBetween(-2.1, 0.1);
    const distToWheel = Math.hypot(x, y + 0.98);
    if (distToWheel >= 0.98 && distToWheel <= 1.46 && !isInsideForbiddenZone(x, y)) {
      return [x, y];
    }
  }
  return [-1.05, -0.25];
}

function generateInitialRandomStickers(): PlacedSticker[] {
  const shuffledStickers = [...homeContent.stickers].sort(
    () => Math.random() - 0.5
  );
  const chosenPoints: [number, number][] = [];
  const borderStickerCount = 3;

  return shuffledStickers.map((sticker, idx) => {
    const preferBorder = idx < borderStickerCount;
    let bestPoint: [number, number] = preferBorder
      ? sampleScreenBorderPoint()
      : sampleAroundWheelPoint();
    let bestMinDist = -1;

    for (let attempt = 0; attempt < 120; attempt += 1) {
      const candidate = preferBorder
        ? sampleScreenBorderPoint()
        : sampleAroundWheelPoint();

      if (isInsideForbiddenZone(candidate[0], candidate[1])) {
        continue;
      }

      const minDistToOthers =
        chosenPoints.length === 0
          ? 999
          : Math.min(
            ...chosenPoints.map(([px, py]) =>
              Math.hypot(candidate[0] - px, candidate[1] - py)
            )
          );

      const targetThreshold = attempt < 60 ? 0.86 : attempt < 95 ? 0.72 : 0.6;

      if (minDistToOthers >= targetThreshold) {
        bestPoint = candidate;
        break;
      }

      if (minDistToOthers > bestMinDist) {
        bestMinDist = minDistToOthers;
        bestPoint = candidate;
      }
    }

    chosenPoints.push(bestPoint);

    const x = Number(bestPoint[0].toFixed(3));
    const y = Number(bestPoint[1].toFixed(3));
    const randomTilt = Number(randomBetween(-0.42, 0.42).toFixed(3));

    return {
      instanceId: `stk-init-${idx}-${sticker.id}`,
      stickerId: sticker.id,
      position: [x, y, 0.142],
      rotation: [0, 0, randomTilt],
      scale: 1,
      autoGenerated: true,
    };
  });
}

export function getSavedStickers(): PlacedSticker[] {
  try {
    const raw = window.localStorage.getItem(STICKER_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as PlacedSticker[];
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }

    const generated = generateInitialRandomStickers();
    window.localStorage.setItem(
      STICKER_STORAGE_KEY,
      JSON.stringify(generated)
    );
    return generated;
  } catch {
    return [];
  }
}

export function savePlacedStickers(stickers: PlacedSticker[]): void {
  try {
    window.localStorage.setItem(STICKER_STORAGE_KEY, JSON.stringify(stickers));
  } catch {
    return;
  }
}